// Package ptyshell is the terminal module's Spawner: real shells on Linux pseudo-terminals (creack/pty).
package ptyshell

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"sync"
	"syscall"

	"github.com/creack/pty"

	"github.com/IhebBelhadj/opsforge/academy/internal/terminal"
)

// Spawner starts each Spec's argv on a new pty.
type Spawner struct{}

var _ terminal.Spawner = Spawner{}

// Spawn starts spec.Argv in spec.Dir with TERM=xterm-256color and spec.Env added to the platform's environment.
func (Spawner) Spawn(spec terminal.Spec) (terminal.Pty, error) {
	if len(spec.Argv) == 0 {
		return nil, errors.New("terminal spec without a command")
	}
	// No context: the shell outlives the request that opened it (the session ends it). argv comes from the
	// platform (Bash), never from a request.
	cmd := exec.Command(spec.Argv[0], spec.Argv[1:]...) //nolint:gosec,noctx // see above
	cmd.Dir = spec.Dir
	cmd.Env = append(append(os.Environ(), "TERM=xterm-256color"), spec.Env...)
	f, err := pty.StartWithSize(cmd, &pty.Winsize{Cols: spec.Cols, Rows: spec.Rows})
	if err != nil {
		return nil, fmt.Errorf("start %s: %w", spec.Argv[0], err)
	}
	p := &shell{f: f, cmd: cmd, exited: make(chan struct{})}
	go func() {
		_ = cmd.Wait() // reaps the shell; its exit status is the session ending, nothing to report
		close(p.exited)
	}()
	return p, nil
}

type shell struct {
	f      *os.File
	cmd    *exec.Cmd
	exited chan struct{}
	once   sync.Once
}

// Read returns the shell's output; the EIO Linux gives once the shell has exited reads as io.EOF.
func (p *shell) Read(b []byte) (int, error) {
	n, err := p.f.Read(b)
	if errors.Is(err, syscall.EIO) {
		return n, errEnded
	}
	return n, err
}

var errEnded = fmt.Errorf("shell ended: %w", os.ErrClosed)

func (p *shell) Write(b []byte) (int, error) { return p.f.Write(b) }

func (p *shell) Resize(cols, rows uint16) error {
	return pty.Setsize(p.f, &pty.Winsize{Cols: cols, Rows: rows})
}

// Close sends SIGHUP to the shell's process group (what closing a terminal does) and releases the pty.
func (p *shell) Close() error {
	var err error
	p.once.Do(func() {
		select {
		case <-p.exited:
		default:
			_ = syscall.Kill(-p.cmd.Process.Pid, syscall.SIGHUP)
		}
		err = p.f.Close()
	})
	return err
}

const bashrc = `# Generated by academy: the browser terminal's shell (Phase 10's, docs/courses/frontend.md "Terminal")
HISTFILE=%[2]s
PS1='\[\e[1m\]lab\[\e[0m\] \W \$ '
opsforge() { %[1]s "$@"; }
if [ -n "${ACADEMY_WORKDIR:-}" ]; then cd "$ACADEMY_WORKDIR"; else cd %[3]s; fi
printf 'Lab terminal in %%s. Lab commands start with opsforge, e.g. opsforge kubectl get nodes\n' "$PWD"
`

// Bash is the lab shell: interactive bash in root (or in $ACADEMY_WORKDIR, an attempt's workspace: see
// terminal.Shells) with an `opsforge` function, history in stateDir. It writes the rcfile to stateDir.
func Bash(root, stateDir string, cols, rows uint16) (terminal.Spec, error) {
	if err := os.MkdirAll(stateDir, 0o700); err != nil {
		return terminal.Spec{}, err
	}
	rc := filepath.Join(stateDir, "academy-bashrc")
	content := fmt.Sprintf(bashrc, shellQuote(filepath.Join(root, "opsforge")),
		shellQuote(filepath.Join(stateDir, "academy-history")), shellQuote(root))
	if err := os.WriteFile(rc, []byte(content), 0o600); err != nil {
		return terminal.Spec{}, err
	}
	return terminal.Spec{Argv: []string{"bash", "--rcfile", rc, "-i"}, Dir: root, Cols: cols, Rows: rows}, nil
}

// shellQuote makes s one literal shell word: single quotes, nothing expands inside.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
